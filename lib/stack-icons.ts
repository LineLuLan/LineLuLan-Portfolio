export type StackIconKey = keyof typeof stackIcons;

function luminance(hex: string) {
  const [r, g, b] = [1, 3, 5].map((offset) => {
    const channel = parseInt(hex.slice(offset, offset + 2), 16) / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  return r! * 0.2126 + g! * 0.7152 + b! * 0.0722;
}

export function stackIconColor(hex: string, panel = '#FFFFFF'): string {
  if (hex === 'currentColor') return hex;
  const color = hex.startsWith('#') ? hex : `#${hex}`;
  const a = luminance(color);
  const b = luminance(panel);
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05) < 3 ? 'currentColor' : color;
}

// Check both the specified panel and the chip's paper background. CSS switches the
// precomputed fallback without hydration or client state.
function prepare(icon: StackIcon) {
  return { ...icon, paths: icon.paths.map((path) => ({
    ...path,
    inkOnLight: stackIconColor(path.fill) === 'currentColor' || stackIconColor(path.fill, '#F8F7F4') === 'currentColor',
    inkOnDark: stackIconColor(path.fill, '#1C1929') === 'currentColor',
  })) };
}
const preparedCustomIcons = Object.fromEntries(Object.entries(customIcons).map(([name, icon]) => [name, prepare(icon)]));
const preparedStackIcons = Object.fromEntries(Object.entries(stackIcons).map(([name, icon]) => [name, prepare(icon)]));

export function getStackIcon(name: string, key?: StackIconKey) {
  return preparedCustomIcons[name] ?? (key ? preparedStackIcons[key] : undefined);
}
